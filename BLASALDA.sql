-- =================================================================
-- 1. TABLA: USUARIOS
-- =================================================================
CREATE TABLE USUARIOS (
    ID_USUARIO NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ESTADO_REGISTRO VARCHAR2(20) NOT NULL,
    USERNAME VARCHAR2(20) NOT NULL,
    PASSWORD VARCHAR2(255) NOT NULL,
    ROL VARCHAR2(10) NOT NULL,

    CONSTRAINT PK_USUARIOS PRIMARY KEY (ID_USUARIO),

    CONSTRAINT CHK_USUARIOS_ESTADO_REGISTRO
        CHECK (ESTADO_REGISTRO IN ('ACTIVO', 'ELIMINADO')),

    CONSTRAINT CHK_USUARIOS_USERNAME
        CHECK (LENGTH(USERNAME) BETWEEN 5 AND 20),

    CONSTRAINT CHK_USUARIOS_PASSWORD
        CHECK (LENGTH(PASSWORD) >= 8),

    CONSTRAINT CHK_USUARIOS_ROL
        CHECK (ROL IN ('ADMIN', 'USER'))
);

-- =================================================================
-- 2. TABLA: HUESPEDES
-- =================================================================
CREATE TABLE HUESPEDES (
    ID_HUESPED NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ESTADO_REGISTRO VARCHAR2(20) NOT NULL,
    NOMBRE VARCHAR2(50) NOT NULL,
    APELLIDO_PATERNO VARCHAR2(50) NOT NULL,
    APELLIDO_MATERNO VARCHAR2(50),
    EMAIL VARCHAR2(100) NOT NULL,
    TELEFONO VARCHAR2(10) NOT NULL,
    TIPO_DOCUMENTO VARCHAR2(20) NOT NULL,
    DOCUMENTO VARCHAR2(20) NOT NULL,
    NACIONALIDAD VARCHAR2(50) NOT NULL,

    CONSTRAINT PK_HUESPEDES PRIMARY KEY (ID_HUESPED),

    CONSTRAINT CHK_HUESPEDES_ESTADO_REGISTRO
        CHECK (ESTADO_REGISTRO IN ('ACTIVO', 'ELIMINADO')),

    CONSTRAINT CHK_HUESPEDES_NOMBRE
        CHECK (LENGTH(NOMBRE) BETWEEN 2 AND 50),

    CONSTRAINT CHK_HUESPEDES_APELLIDO_PATERNO
        CHECK (LENGTH(APELLIDO_PATERNO) BETWEEN 2 AND 50),
        
        CONSTRAINT CHK_HUESPEDES_APELLIDO_MATERNO
        CHECK (LENGTH(APELLIDO_MATERNO) BETWEEN 2 AND 50),

    CONSTRAINT CHK_HUESPEDES_TELEFONO
        CHECK (REGEXP_LIKE(TELEFONO, '^[0-9]{10}$')),

    CONSTRAINT CHK_HUESPEDES_TIPO_DOCUMENTO
        CHECK (TIPO_DOCUMENTO IN ('INE', 'DNI', 'PASAPORTE', 'CEDULA_PROFESIONAL', 'LICENCIA_CONDUCIR'))
);

-- =================================================================
-- 3. TABLA: HABITACIONES
-- =================================================================
CREATE TABLE HABITACIONES (
    ID_HABITACION NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ESTADO_HABITACION VARCHAR2(20) NOT NULL,
    ESTADO_REGISTRO VARCHAR2(20) NOT NULL,
    NUMERO_HABITACION NUMBER NOT NULL,
    TIPO VARCHAR2(30) NOT NULL,
    PRECIO NUMBER(10,2) NOT NULL,
    CAPACIDAD NUMBER NOT NULL,

    CONSTRAINT PK_HABITACIONES PRIMARY KEY (ID_HABITACION),

    CONSTRAINT CHK_HABITACIONES_ESTADO_REGISTRO
        CHECK (ESTADO_REGISTRO IN ('ACTIVO', 'ELIMINADO')),

    CONSTRAINT CHK_HABITACIONES_ESTADO_HABITACION
        CHECK (ESTADO_HABITACION IN (
            'DISPONIBLE',
            'OCUPADA',
            'LIMPIEZA',
            'MANTENIMIENTO'
        )),

    CONSTRAINT CHK_HABITACIONES_NUMERO
        CHECK (NUMERO_HABITACION > 0),

    CONSTRAINT CHK_HABITACIONES_TIPO
        CHECK (TIPO IN (
            'INDIVIDUAL',
            'DOBLE',
            'SUITE',
            'DELUXE',
            'PRESIDENCIAL'
        )),

    CONSTRAINT CHK_HABITACIONES_PRECIO
        CHECK (PRECIO > 0),

    CONSTRAINT CHK_HABITACIONES_CAPACIDAD
        CHECK (CAPACIDAD >= 1)
);

-- =================================================================
-- 4. TABLA: RESERVACIONES
-- =================================================================
CREATE TABLE RESERVACIONES (
    ID_RESERVA NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ESTADO_REGISTRO VARCHAR2(20) NOT NULL,
    ESTADO_RESERVA VARCHAR2(20) NOT NULL,
    ID_HUESPED NUMBER NOT NULL,
    ID_HABITACION NUMBER NOT NULL,

    CONSTRAINT PK_RESERVACIONES PRIMARY KEY (ID_RESERVA),

    CONSTRAINT CHK_RESERVACIONES_ESTADO_REGISTRO
        CHECK (ESTADO_REGISTRO IN ('ACTIVO', 'ELIMINADO')),

    CONSTRAINT CHK_RESERVACIONES_ESTADO_RESERVA
        CHECK (ESTADO_RESERVA IN (
            'CONFIRMADA',
            'EN_CURSO',
            'FINALIZADA',
            'CANCELADA'
        ))
);